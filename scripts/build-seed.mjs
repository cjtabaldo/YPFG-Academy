// Builds supabase/seed.sql from /content. Seeding never overwrites rows that
// already exist, so edits made in the app's editor are kept.
import fs from 'node:fs';
import path from 'node:path';
import { loadContent, ROOT } from './content-lib.mjs';

const c = loadContent();
const lit = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v) && v.every((x) => typeof x === 'string') && v.__textArray) return `'{}'`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a) => `array[${a.map((x) => lit(x)).join(',')}]::text[]`;
const rows = (table, cols, items, map, conflict = 'id') => {
  if (!items.length) return '';
  const vals = items.map((it) => `(${map(it).join(', ')})`).join(',\n  ');
  return `insert into public.${table} (${cols.join(', ')}) values\n  ${vals}\non conflict (${conflict}) do nothing;\n\n`;
};

let sql = `-- Generated by scripts/build-seed.mjs from /content. Do not edit by hand.\n-- Outline version: ${c.outline_version}\nbegin;\n`;
sql += `update public.app_settings set outline_version = ${lit(c.outline_version)} where id = 1 and outline_version <> ${lit(c.outline_version)};\n\n`;
sql += rows('outline_topics', ['id', 'portion', 'title', 'items', 'items_verified', 'course', 'sort'], c.topics, (t) => [lit(t.id), lit(t.portion), lit(t.title), lit(t.items), lit(t.items_verified), lit(t.course), lit(t.sort)]);
sql += rows('outline_subtopics', ['id', 'topic_id', 'title', 'sort', 'cc_target', 'lp_target', 'verify_note'], c.subtopics, (s) => [lit(s.id), lit(s.topic_id), lit(s.title), lit(s.sort), lit(s.cc_target), lit(s.lp_target), lit(s.verify_note)]);
sql += rows('units', ['id', 'portion', 'title', 'course', 'topic_ids', 'sort'], c.units, (u) => [lit(u.id), lit(u.portion), lit(u.title), lit(u.course), arr(u.topic_ids), lit(u.sort)]);
sql += rows('lessons', ['id', 'unit_id', 'title', 'kind', 'subtopic_ids', 'sort'], c.lessons, (l) => [lit(l.id), lit(l.unit_id), lit(l.title), lit(l.kind), arr(l.subtopic_ids), lit(l.sort)]);
sql += rows('terms', ['id', 'term', 'definition', 'subtopic_id', 'citation', 'outline_version', 'status'], c.terms, (t) => [lit(t.id), lit(t.term), lit(t.definition), lit(t.subtopic_id), lit(t.citation), lit(t.outline_version), lit(t.status)]);
sql += rows('concept_cards', ['id', 'subtopic_id', 'title', 'body', 'example', 'memory_hook', 'term_ids', 'citation', 'outline_version', 'status'], c.cards, (k) => [lit(k.id), lit(k.subtopic_id), lit(k.title), lit(k.body), lit(k.example), lit(k.memory_hook), arr(k.term_ids), lit(k.citation), lit(k.outline_version), lit(k.status)]);
sql += rows('exam_forms', ['id', 'portion', 'name', 'status'], c.forms, (f) => [lit(f.id), lit(f.portion), lit(f.name), lit(f.status)]);
const qcols = ['id', 'pool', 'exam_form_id', 'is_pretest', 'portion', 'topic_id', 'subtopic_id', 'outline_version', 'course', 'exercise_type', 'difficulty', 'level', 'prompt', 'options', 'correct', 'explanation', 'wrong_explanations', 'memory_hook', 'formula', 'worked_steps', 'citation', 'fact_key', 'status'];
sql += rows('questions', qcols, c.questions, (q) => qcols.map((k) => (['options', 'correct', 'wrong_explanations', 'worked_steps'].includes(k) ? `'${JSON.stringify(q[k]).replace(/'/g, "''")}'::jsonb` : lit(q[k]))));
sql += rows('verify_items', ['key', 'category', 'label', 'value', 'note', 'sort'], c.verify, (v) => [lit(v.key), lit(v.category), lit(v.label), lit(v.value), lit(v.note), lit(v.sort)], 'key');
sql += 'commit;\n';
fs.writeFileSync(path.join(ROOT, 'supabase/seed.sql'), sql);

console.log(`Wrote supabase/seed.sql (${(sql.length / 1024).toFixed(0)} KB).`);
