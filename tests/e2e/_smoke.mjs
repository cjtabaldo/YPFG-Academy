import { chromium } from '@playwright/test';
import { makeUser, resetDb } from '../backend/helpers.mjs';
const OUT = process.env.OUT;
resetDb();
await makeUser('owner@test.dev', 'admin');
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
await page.goto('http://localhost:4173/');
await page.screenshot({ path: `${OUT}/01-signin.png` });
await page.getByLabel('Email').fill('owner@test.dev');
await page.getByLabel('Password').fill('Test-password-123');
await page.getByRole('button', { name: 'Sign in' }).click();
await page.getByText('Welcome to YPFG Academy.').waitFor({ timeout: 15000 });
await page.screenshot({ path: `${OUT}/02-welcome.png` });
await page.getByRole('button', { name: "Let's go" }).click();
await page.screenshot({ path: `${OUT}/03-disclaimer.png` });
await page.getByRole('checkbox').check();
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByLabel('Your name').fill('Chris Owner');
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByRole('button', { name: 'Continue' }).click(); // goal
await page.getByRole('button', { name: 'Continue' }).click(); // time
await page.getByLabel('Target exam date').fill('2027-01-15');
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByLabel('School name').fill('Silver State School of Real Estate');
await page.getByRole('button', { name: 'Continue' }).click();
await page.getByRole('button', { name: /Skip/ }).click();
await page.screenshot({ path: `${OUT}/04-placement-choice.png` });
await page.getByRole('button', { name: 'Finish setup' }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/05-home.png`, fullPage: true });
await page.getByRole('link', { name: /Real or Personal/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/06-card.png` });
console.log('errors:', errors);
await browser.close();
